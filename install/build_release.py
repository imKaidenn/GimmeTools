def make_installer(ver: str) -> None:
    step("Installer script (Inno Setup)...")
    iss = DIST / "GimmeTools-Setup.iss"
    iss.write_text(ISS_TEMPLATE.format(VERSION=ver), encoding="utf-8")
    print(f"    OK: {iss.name}")
    if shutil.which("iscc"):
        step("Compiling installer with iscc...")
        if run(["iscc", str(iss)], cwd=str(DIST)) == 0:
            print("    OK: installer built")
        else:
            print("    WARN: iscc failed — see output above")
    else:
        print("    iscc not on PATH — install Inno Setup 6 and run:")
        print(f"      iscc {iss}")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--skip-exe", action="store_true",
                        help="skip PyInstaller; stage a source-based portable build")
    args = parser.parse_args()

    ver = version()
    print("=" * 50)
    print(f"  GimmeTools release builder — v{ver}")
    print("=" * 50)

    DIST.mkdir(exist_ok=True)
    with_exe = not args.skip_exe
    if with_exe and not build_exe():
        print("\n  Falling back to source-based portable build (--skip-exe).")
        with_exe = False

    stage_runtime(with_exe)
    make_zip(ver)
    if with_exe:
        make_installer(ver)

    print("\n" + "=" * 50)
    print("  Release artifacts are in dist\\")
    print("=" * 50)
    return 0


if __name__ == "__main__":
    sys.exit(main())
